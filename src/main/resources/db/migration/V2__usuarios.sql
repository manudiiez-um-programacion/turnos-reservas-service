-- Usuarios finales (#9).
--
-- Decidido en el ADR 0002 del repo de catalogo (turnos-catalogo-sync#59, D1):
-- los usuarios finales viven en ESTE servicio. El de catalogo no tiene
-- usuarios ni login, solo valida el JWT que emitimos aca.
--
-- El modelo tiene que ser compatible con el contrato que genera JHipster
-- (login, password, firstName, lastName, email, imageUrl, langKey), aunque
-- JHipster no se usa como herramienta (ver CLAUDE.md §9).

-- login y email se normalizan a minusculas en la aplicacion antes de guardar
-- (igual que JHipster), asi que un UNIQUE comun alcanza para la unicidad
-- case-insensitive: no hace falta un indice funcional sobre lower(...).
--
-- password_hash en VARCHAR(120): un hash Argon2id con los parametros de #9
-- (ver PasswordEncoderConfig) mide 97 caracteres, 105 con el prefijo
-- "{argon2}" que agrega el DelegatingPasswordEncoder. Es bastante mas que los
-- 60 caracteres fijos de BCrypt. 120 deja margen sin ser arbitrario.
--
-- external_patient_id es el identificador estable y opaco que este servicio
-- envia a la catedra como externalPatientId (§4 de la referencia): no es el
-- login (podria cambiar) ni el id autoincremental (filtra informacion). Se
-- genera una vez, en el alta, y no cambia.
CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_patient_id VARCHAR(100) NOT NULL,
    login VARCHAR(50) NOT NULL,
    password_hash VARCHAR(120) NOT NULL,
    first_name VARCHAR(50),
    last_name VARCHAR(50),
    email VARCHAR(191) NOT NULL,
    image_url VARCHAR(256),
    lang_key VARCHAR(10) NOT NULL,
    activated BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_usuario_login UNIQUE (login),
    CONSTRAINT uk_usuario_email UNIQUE (email),
    CONSTRAINT uk_usuario_external_patient_id UNIQUE (external_patient_id)
);

COMMENT ON TABLE usuario IS
    'Usuarios finales de la app KMP. Propiedad exclusiva de este servicio (ADR 0002 D1).';
COMMENT ON COLUMN usuario.external_patient_id IS
    'Identificador estable y opaco enviado a la catedra como externalPatientId.';

CREATE TRIGGER trg_usuario_set_updated_at
    BEFORE UPDATE ON usuario
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();

-- Autoridades del usuario (ROLE_USER por ahora). Tabla de coleccion simple y
-- sin catalogo de roles propio a proposito: el rol administrador es opcional
-- y esta fuera de alcance de #9, y los valores posibles son una constante del
-- codigo, no algo que se administre desde la base.
CREATE TABLE usuario_autoridad (
    usuario_id BIGINT NOT NULL REFERENCES usuario (id) ON DELETE CASCADE,
    autoridad VARCHAR(50) NOT NULL,
    PRIMARY KEY (usuario_id, autoridad)
);
