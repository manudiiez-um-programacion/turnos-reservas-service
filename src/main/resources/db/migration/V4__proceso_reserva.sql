-- Proceso de reserva local y su maquina de estados (#26, §4.2 y §10 del
-- enunciado: la maquina de estados queda explicitamente a cargo del alumno).
--
-- Es la unidad de trabajo que correlaciona lo que pasa por REST (holds,
-- confirmacion inicial) con lo que llega por Kafka (#29, #31, #35), y lo que
-- sobrevive a un reinicio del servicio (#37). reservation_process_id y
-- hold_id son UNIQUE porque son, respectivamente, la clave de correlacion de
-- Kafka y el identificador con el que se confirma el hold por REST: cada uno
-- identifica un unico proceso.
--
-- professional_id NO es una copia del catalogo (§4.2 prohibe esa copia):
-- professional_nombre_historico y professional_apellido_historico son el
-- nombre y apellido del profesional segun el catalogo al momento de crear el
-- hold (#27), un dato descriptivo congelado de ESTE proceso, nunca una fuente
-- para validar una operacion nueva.
--
-- expires_at es siempre el que informa la catedra (hold o confirmacion
-- inicial): conservarlo aca no extiende el TTL (§9 de la referencia).
--
-- request_event_id y reservation_id son nulos mientras el proceso no llego a
-- ese punto del flujo: el primero recien existe tras #29
-- (AdditionalInformationRequested), el segundo recien tras #31
-- (AppointmentConfirmed).
CREATE TABLE proceso_reserva (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_process_id VARCHAR(100) NOT NULL,
    hold_id VARCHAR(100) NOT NULL,
    usuario_id BIGINT NOT NULL REFERENCES usuario (id),
    professional_id BIGINT NOT NULL,
    professional_nombre_historico VARCHAR(100) NOT NULL,
    professional_apellido_historico VARCHAR(100) NOT NULL,
    fecha DATE NOT NULL,
    hora_inicio TIME NOT NULL,
    estado VARCHAR(50) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    request_event_id VARCHAR(100),
    reservation_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_proceso_reserva_reservation_process_id UNIQUE (reservation_process_id),
    CONSTRAINT uk_proceso_reserva_hold_id UNIQUE (hold_id)
);

COMMENT ON TABLE proceso_reserva IS
    'Proceso de reserva local (#26): correlaciona REST y Kafka, y sobrevive a reinicios.';
COMMENT ON COLUMN proceso_reserva.professional_nombre_historico IS
    'Nombre del profesional segun el catalogo al momento del hold. Dato historico, nunca catalogo vigente (§4.2).';
COMMENT ON COLUMN proceso_reserva.professional_apellido_historico IS
    'Apellido del profesional segun el catalogo al momento del hold. Dato historico, nunca catalogo vigente (§4.2).';
COMMENT ON COLUMN proceso_reserva.expires_at IS
    'TTL que informa la catedra (hold o confirmacion inicial). Conservarlo aca no lo extiende (§9 de la referencia).';

CREATE TRIGGER trg_proceso_reserva_set_updated_at
    BEFORE UPDATE ON proceso_reserva
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();

-- Historial de transiciones (#26, §7 del enunciado: "los instantes de cada
-- transicion"). Tabla de coleccion simple como usuario_autoridad y no un
-- JSON ni columnas por estado: cada fila es un punto del historial, no el
-- proceso completo en ese momento.
--
-- Sin created_at/updated_at ni trigger: cada fila, una vez insertada, nunca
-- se actualiza (una transicion nueva agrega una fila, no modifica una
-- existente).
CREATE TABLE proceso_reserva_transicion (
    proceso_reserva_id BIGINT NOT NULL REFERENCES proceso_reserva (id) ON DELETE CASCADE,
    estado VARCHAR(50) NOT NULL,
    ocurrido_en TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (proceso_reserva_id, estado, ocurrido_en)
);

COMMENT ON TABLE proceso_reserva_transicion IS
    'Historial de transiciones de un proceso_reserva (#26): a que estado paso y cuando.';
